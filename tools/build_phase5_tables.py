#!/usr/bin/env python3
"""Generate the Phase 5 tables from the registers (never edit the outputs by hand).

Run from the project root:
    py tools\\build_phase5_tables.py
Writes 05-integration/risk-rescoring.md and 05-integration/kpi-results.md.
tools/validate_phase5.py regenerates both in memory and fails if they are out of date.
Standard library only.
"""
import csv
import sys
from pathlib import Path


def rows(root, rel):
    with (Path(root) / rel).open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def arrow(a, b):
    a, b = int(a), int(b)
    return "up" if b > a else "down" if b < a else "unchanged"


def render_rescoring(root):
    risks = rows(root, "02-risk/risk-register.csv")
    out = ["# Risk re-scoring (Phase 5)", "",
           "Generated by `tools/build_phase5_tables.py` from `02-risk/risk-register.csv`. Do not edit by hand.",
           "Before = Phase 2 assessment (R-17 added in Phase 3). After = re-scored on 2026-11-17 with the",
           "evidence of Phases 3 and 4. Scales and bands: POL-09.", "",
           "| Risk | Title | Before (L x I) | After (L x I) | Change | Drivers | Basis |",
           "|---|---|---|---|---|---|---|"]
    for r in risks:
        out.append(f"| {r['risk_id']} | {r['title']} | {r['current_score']} {r['current_level']} "
                   f"({r['current_likelihood']} x {r['current_impact']}) | {r['rescored_score']} {r['rescored_level']} "
                   f"({r['rescored_likelihood']} x {r['rescored_impact']}) | "
                   f"{arrow(r['current_score'], r['rescored_score'])} | {r['rescore_drivers']} | {r['rescore_basis']} |")
    levels = ["Critical", "High", "Medium", "Low"]
    out += ["", "## Count by level", "", "| Level | Before | After | Target |", "|---|---|---|---|"]
    for lv in levels:
        out.append(f"| {lv} | {sum(r['current_level'] == lv for r in risks)} | "
                   f"{sum(r['rescored_level'] == lv for r in risks)} | {sum(r['target_level'] == lv for r in risks)} |")
    out.append(f"| Total | {len(risks)} | {len(risks)} | {len(risks)} |")
    changed = [r for r in risks if r["current_score"] != r["rescored_score"]]
    out += ["", f"{len(changed)} of {len(risks)} risks changed score: "
            + ", ".join(f"{r['risk_id']} {r['current_score']} -> {r['rescored_score']}" for r in changed) + ".", ""]
    return "\n".join(out)


def render_kpis(root):
    kpis = rows(root, "01-governance/kpi-register.csv")
    out = ["# KPI results (Phase 5)", "",
           "Generated by `tools/build_phase5_tables.py` from `01-governance/kpi-register.csv`. Do not edit by hand.",
           "Value types: **measured in the lab** (from lab evidence), **simulated** (tabletop step),",
           "**derived from the register**, **not measured** (no lab equivalent). The incident timeline is a",
           "compressed lab simulation: real detection, decisions and notifications take hours, not seconds.", "",
           "| KPI | Name | Target | Value | Type | Evidence | Note |", "|---|---|---|---|---|---|---|"]
    for k in kpis:
        out.append(f"| {k['kpi_id']} | {k['name']} | {k['target']} | {k['measured_value']} | {k['value_type']} | "
                   f"{k['evidence']} | {k['measurement_note']} |")
    counts = {}
    for k in kpis:
        counts[k["value_type"]] = counts.get(k["value_type"], 0) + 1
    out += ["", "Summary: " + ", ".join(f"{v} {t}" for t, v in sorted(counts.items())) + ".", ""]
    return "\n".join(out)


def main():
    root = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
    d = root / "05-integration"
    d.mkdir(exist_ok=True)
    (d / "risk-rescoring.md").write_text(render_rescoring(root), encoding="utf-8", newline="\n")
    (d / "kpi-results.md").write_text(render_kpis(root), encoding="utf-8", newline="\n")
    print(f"Wrote {d / 'risk-rescoring.md'} and {d / 'kpi-results.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
