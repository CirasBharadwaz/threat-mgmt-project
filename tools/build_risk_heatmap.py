#!/usr/bin/env python3
"""Build 02-risk/risk-heatmap.md from 02-risk/risk-register.csv.

Run from the project root:
    py tools\\build_risk_heatmap.py

The heat map is generated, never edited by hand. tools/validate_phase2.py
regenerates it in memory and fails if the file on disk is out of date.
Standard library only.
"""
import csv
import sys
from pathlib import Path

LEVELS = [(1, 4, "Low"), (5, 9, "Medium"), (10, 16, "High"), (20, 25, "Critical")]
LIKELIHOOD = {1: "Rare", 2: "Unlikely", 3: "Possible", 4: "Likely", 5: "Almost certain"}
IMPACT = {1: "Negligible", 2: "Minor", 3: "Moderate", 4: "Major", 5: "Severe"}


def level_for(score):
    for low, high, name in LEVELS:
        if low <= score <= high:
            return name
    return "Invalid"


def load_risks(root):
    path = Path(root) / "02-risk" / "risk-register.csv"
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def grid(risks, prefix):
    cells = {}
    for r in risks:
        try:
            lk = int(r[f"{prefix}_likelihood"])
            im = int(r[f"{prefix}_impact"])
        except (KeyError, ValueError):
            continue
        cells.setdefault((lk, im), []).append(r["risk_id"])
    lines = [
        "| Likelihood \\ Impact | 1 Negligible | 2 Minor | 3 Moderate | 4 Major | 5 Severe |",
        "|---|---|---|---|---|---|",
    ]
    for lk in range(5, 0, -1):
        row = [f"**{lk} {LIKELIHOOD[lk]}**"]
        for im in range(1, 6):
            ids = cells.get((lk, im), [])
            band = level_for(lk * im)[0]  # L, M, H, C
            row.append(f"{band}: " + ", ".join(sorted(ids)) if ids else f"{band}")
        lines.append("| " + " | ".join(row) + " |")
    return lines


def counts(risks, prefix):
    out = {name: 0 for _, _, name in LEVELS}
    for r in risks:
        try:
            out[level_for(int(r[f"{prefix}_likelihood"]) * int(r[f"{prefix}_impact"]))] += 1
        except (KeyError, ValueError):
            pass
    return out


def render(root):
    risks = load_risks(root)
    cur, tgt = counts(risks, "current"), counts(risks, "target")
    rescored = all(r.get("rescored_likelihood") for r in risks)
    res = counts(risks, "rescored") if rescored else None
    lines = [
        "# Risk heat map",
        "",
        "Generated by `tools/build_risk_heatmap.py` from `risk-register.csv`. Do not edit by hand.",
        "Scales and bands are defined in POL-09. Cell prefix shows the band: L Low (1-4), M Medium (5-9),",
        "H High (10-16), C Critical (20-25).",
        "",
        "## Before: Phase 2 assessment (existing controls)",
        "",
        *grid(risks, "current"),
        "",
    ]
    if rescored:
        lines += ["## After: re-scored with the evidence of Phases 3 and 4", "",
                  *grid(risks, "rescored"), ""]
    lines += [
        "## Target risk (after all planned treatment actions)",
        "",
        *grid(risks, "target"),
        "",
        "## Count by level",
        "",
        "| Level | Before (Phase 2) | " + ("After (re-scored) | " if rescored else "") + "Target |",
        "|---|---|" + ("---|" if rescored else "") + "---|",
    ]
    for _, _, name in reversed(LEVELS):
        lines.append(f"| {name} | {cur[name]} | " + (f"{res[name]} | " if rescored else "") + f"{tgt[name]} |")
    n = len(risks)
    lines.append(f"| Total | {n} | " + (f"{n} | " if rescored else "") + f"{n} |")
    lines.append("")
    return "\n".join(lines)


def main():
    root = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
    out = root / "02-risk" / "risk-heatmap.md"
    out.write_text(render(root), encoding="utf-8", newline="\n")
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
